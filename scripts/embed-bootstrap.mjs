// GENERATES src/framework/bootstrapCss.ts — vendored Bootstrap 5 + Bootstrap Icons
// CSS as a JS string, with the icon webfont inlined as a data: URI.
// Run automatically via the "prepare" / "prestart" / "prepackage" npm scripts.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const R = (p) => resolve(root, p);

const bootstrapCss = readFileSync(R("node_modules/bootstrap/dist/css/bootstrap.min.css"), "utf8");

let iconsCss = readFileSync(R("node_modules/bootstrap-icons/font/bootstrap-icons.css"), "utf8");
const woff2 = readFileSync(R("node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff2")).toString("base64");
// Replace the whole `src: url(...woff2...) ..., url(...woff...) ...;` with a single inlined woff2.
iconsCss = iconsCss.replace(
    /src:\s*url\([^)]*\.woff2[^)]*\)\s*format\("woff2"\)[^;]*;/,
    `src: url("data:font/woff2;base64,${woff2}") format("woff2");`
);

const combined = `${bootstrapCss}\n${iconsCss}`;
const out = `/* GENERATED by scripts/embed-bootstrap.mjs — do not edit.
 * Bootstrap ${JSON.parse(readFileSync(R("node_modules/bootstrap/package.json"), "utf8")).version} +
 * Bootstrap Icons ${JSON.parse(readFileSync(R("node_modules/bootstrap-icons/package.json"), "utf8")).version}
 * (icon webfont inlined). Injected at runtime by framework/bootstrapRuntime.ts. */
export const BOOTSTRAP_CSS: string = ${JSON.stringify(combined)};
`;
writeFileSync(R("src/framework/bootstrapCss.ts"), out);
console.log(`embed-bootstrap: wrote src/framework/bootstrapCss.ts (${(out.length / 1024).toFixed(0)} KB)`);
